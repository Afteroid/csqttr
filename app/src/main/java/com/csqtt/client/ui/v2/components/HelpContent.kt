package com.csqtt.client.ui.v2.components

internal data class HelpSection(val title: String, val points: List<String>)

/** Descriptions follow the mode explanations in the legacy CSQTT Debug dialogs. */
internal fun helpSections(title: String, fallback: String): List<HelpSection> = when(title) {
    "Ручные хеши" -> listOf(
        HelpSection("Формат", listOf("Ссылка вида vk.com/call/join/… или готовый хеш длиной от 16 символов.")),
        HelpSection("Заполнение", listOf("Доступно шесть полей. Для каждого есть вставка из буфера и очистка.", "Сохраните изменения кнопкой «Сохранить».")),
        HelpSection("Проверка", listOf("Проверяет доступность самих звонков. Зелёный — хеш активен, красный — недействителен.", "Проверка хешей не проверяет VPS или пароль туннеля.")),
    )
    "Способ входа" -> listOf(
        HelpSection("Пароль", listOf("Логин и пароль пользователя SSH на VPS. SSH-порт указывается рядом с адресом сервера.")),
        HelpSection("SSH-ключ", listOf("Укажите приватный ключ OpenSSH или PEM.", "Если ключ зашифрован, добавьте его пароль. SSH-сертификат заполняется только если он используется на сервере.")),
    )
    "Режим хешей" -> listOf(
        HelpSection("Ручные хеши", listOf("Ссылки на звонки или готовые хеши вводятся в шесть полей.", "Вход в аккаунт VK не требуется. Доступность хешей можно проверить отдельно.")),
        HelpSection("Авто API", listOf("Использует токен аккаунта VK и метод calls.start для создания звонков.", "Звонки создаются при подключении и завершаются после отключения.")),
        HelpSection("Авто ВК", listOf("Использует авторизованный аккаунт и браузерную цепочку VK Calls.", "Создатель удерживает один звонок до отключения. Для этого режима нужен вход в VK.")),
    )
    "Режим кредов" -> listOf(
        HelpSection("Авто", listOf("Гостевая цепочка VK Calls получает TURN-сессии напрямую.", "Обычно работает без капчи.")),
        HelpSection("Капча", listOf("Старый способ через эмуляцию браузерного клиента.", "VK может потребовать капчу. Если автоматическое решение не сработает, откроется ручное подтверждение.")),
        HelpSection("Авто ВК", listOf("Получает TURN-креды под авторизованным аккаунтом VK.", "Работает вместе с режимом хешей «Авто ВК». Создатель удерживает звонок до отключения.", "Если отдельная сессия не выдаст креды, её группа перейдёт на гостевой режим «Авто».")),
    )
    "Режим SRTP" -> listOf(
        HelpSection("Авто", listOf("Сначала используется DTLS-SRTP; если рукопожатие недоступно, выполняется переход к WRAP-SRTP.")),
        HelpSection("DTLS-SRTP", listOf("Настоящее DTLS-рукопожатие с последующей передачей SRTP.")),
        HelpSection("WRAP-SRTP", listOf("SRTP-обёртка без DTLS-рукопожатия. Альтернатива при проблемах с DTLS.")),
    )
    "Транспорт" -> listOf(
        HelpSection("UDP", listOf("Основной транспорт до TURN. Обычно даёт меньшую задержку.")),
        HelpSection("TCP", listOf("Соединение с TURN по TCP/TLS. Используйте, если UDP недоступен.", "Очередь TCP может увеличивать задержку при нагрузке. Автоматического переключения на UDP нет.")),
    )
    "Потоки" -> listOf(
        HelpSection("Количество", listOf("Число параллельных TURN-потоков выбранного профиля.", "Минимум — 10, шаг — 10. Верхний предел зависит от режима и ограничений профиля.")),
        HelpSection("При изменении", listOf("Больше потоков увеличивает нагрузку на телефон и сеть. Максимальное число не гарантирует более высокую скорость.", "Настройка сохраняется в профиле подключения; к данным VPS для деплоя она не относится.")),
    )
    else -> listOf(HelpSection("", fallback.split(Regex("\\n\\s*\\n")).filter(String::isNotBlank)))
}
